export function getProductUnitPrice(product: Product, quantity: number): number {
  if (!product.volumePricing || product.volumePricing.length === 0) {
    return product.unitPriceEtb;
  }
  const matchedTier = product.volumePricing
    .slice()
    .reverse()
    .find((t) => quantity >= t.minQuantity);
  return matchedTier ? matchedTier.unitPriceEtb : product.unitPriceEtb;
}

